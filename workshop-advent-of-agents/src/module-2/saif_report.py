"""Generate a SAIF threat-model report for the inbox agent from google/saif-data.

The Strands counterpart of `launch_saif_demo.sh`: instead of scanning a cloud
project, it inspects the controls configured on the agent, answers the SAIF
self-assessment for the Model Consumer persona, and maps every relevant risk to
its catalog controls, marking each as implemented here or as a gap.

Usage:
    uv run src/module-2/saif_report.py                      # clones saif-data on first run
    uv run src/module-2/saif_report.py --catalog ./saif-data
"""

import argparse
import subprocess
from pathlib import Path

import yaml

from inbox_agent import build_session
from saif_controls import OUTPUT_SANITIZER_CONTROLS

HERE = Path(__file__).parent
DEFAULT_CATALOG = HERE / ".saif-data"
REPORT_PATH = HERE / "SAIF_REPORT.md"
SAIF_REPO = "https://github.com/google/saif-data.git"
PERSONA = "personaModelConsumer"

# Answers to the SAIF self-assessment for this agent, with the evidence behind each.
ANSWERS: dict[str, tuple[str, str]] = {
    "Q4": ("Maybe", "audit.jsonl stores tool inputs (email bodies) with no retention policy yet"),
    "Q5": ("Maybe", "single model via Bedrock; no formal model/dataset inventory"),
    "Q6": ("Maybe", "Bedrock access via IAM credentials; not least-privilege scoped for the lab"),
    "Q9": ("No", "no rate limiting or abuse detection in front of the agent"),
    "Q10": ("Maybe", "hooks enforce permissions, but tools are in-process stubs"),
    "Q11": ("Yes", "attack_eval.py runs injection, forged-history and deception cases"),
    "Q12": ("Yes", "the agent can send email on Alice's behalf (send_email)"),
}

# SAIF "Focus on Agents" components -> where they live in this module.
COMPONENTS = [
    ("Perception (input transformation)", "system prompt + user request + tool results", "UntrustedContentFilter"),
    ("Reasoning core", "Strands agent loop on Claude (Bedrock)", "model robustness (creator control)"),
    ("Orchestration: tools", "list_inbox, read_email, search_contacts, send_email", "TaskPermissions, HumanApproval"),
    ("Orchestration: memory", "agent.messages (conversation history)", "trusted-history boundary (forged-history case)"),
    ("Response rendering (output transformation)", "markdown shown to Alice", "sanitize_output()"),
    ("Observability", "every tool call and control decision", "AuditLog -> audit.jsonl"),
]


def load_catalog(path: Path) -> dict:
    if not (path / "yaml").is_dir():
        print(f"Cloning {SAIF_REPO} into {path} ...")
        subprocess.run(["git", "clone", "--depth", "1", "--quiet", SAIF_REPO, str(path)], check=True)
    # safe_load only: the catalog is downloaded data and must never be executed.
    read = lambda name: yaml.safe_load((path / "yaml" / f"{name}.yaml").read_text())  # noqa: E731
    return {
        "risks": {r["id"]: r for r in read("risks")["risks"]},
        "controls": {c["id"]: c for c in read("controls")["controls"]},
        "questions": read("self-assessment")["selfAssessment"]["questions"],
    }


def implemented_controls() -> dict[str, str]:
    """SAIF control id -> the Strands component that implements it, read from a live session."""
    session = build_session("report", task="reply", safe=True, verbose=False, callback_handler=None)
    found = {cid: type(c).__name__ for c in [*session.controls, session.audit] for cid in c.saif_controls}
    found.update({cid: "sanitize_output()" for cid in OUTPUT_SANITIZER_CONTROLS})
    found["controlAdversarialTrainingAndTesting"] = "attack_eval.py"  # a process control, not a hook
    return found


def relevant_risks(questions: list[dict], catalog_risks: dict) -> dict[str, list[str]]:
    """Risk id -> self-assessment questions whose answer makes it relevant."""
    risks: dict[str, list[str]] = {}
    for q in questions:
        if PERSONA not in q["personas"] or q["id"] not in ANSWERS:
            continue
        answer = ANSWERS[q["id"]][0]
        # PyYAML reads the bare Yes/No in `relevance` as booleans.
        relevance = {{True: "Yes", False: "No"}.get(v, v) for v in q["relevance"]}
        if answer in relevance:
            for risk in q["risks"]:
                if PERSONA in catalog_risks[risk].get("personas", []):
                    risks.setdefault(risk, []).append(q["id"])
    return risks


def build_report(catalog: dict, implemented: dict[str, str]) -> str:
    risks = relevant_risks(catalog["questions"], catalog["risks"])
    lines = [
        "# SAIF threat-model report — inbox-assistant",
        "",
        "Generated by `saif_report.py` from [google/saif-data](https://github.com/google/saif-data). "
        f"Persona: **{PERSONA}**.",
        "",
        "## Agent components",
        "",
        "| SAIF component | In this agent | Control |",
        "|---|---|---|",
        *[f"| {a} | {b} | {c} |" for a, b, c in COMPONENTS],
        "",
        "## Self-assessment",
        "",
        "| Q | Question | Answer | Evidence |",
        "|---|---|---|---|",
    ]
    for q in catalog["questions"]:
        if q["id"] in ANSWERS:
            answer, evidence = ANSWERS[q["id"]]
            lines.append(f"| {q['id']} | {q['text'][0].strip()} | {answer} | {evidence} |")

    lines += ["", "## Relevant risks and controls", ""]
    total = covered = 0
    for risk_id in sorted(risks, key=lambda r: (r not in {"RA", "SDD", "PIJ"}, r)):
        risk = catalog["risks"][risk_id]
        lines += [
            f"### {risk_id} — {risk['title']}",
            "",
            f"{risk['shortDescription'][0].strip()}",
            "",
            f"Flagged by: {', '.join(risks[risk_id])}",
            "",
            "| Control | Status |",
            "|---|---|",
        ]
        for cid in risk.get("controls", []):
            title = catalog["controls"].get(cid, {}).get("title", cid)
            owners = catalog["controls"].get(cid, {}).get("personas", [])
            if cid in implemented:
                total, covered = total + 1, covered + 1
                status = f"✅ implemented by `{implemented[cid]}`"
            elif PERSONA not in owners:
                status = "⬜ model-creator responsibility"
            else:
                total += 1
                status = "❌ gap"
            lines.append(f"| {title} | {status} |")
        lines.append("")

    lines.insert(4, f"**Coverage:** {covered}/{total} consumer-owned risk→control mappings implemented in this module.\n")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a SAIF report for the inbox agent")
    parser.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG, help="path to a saif-data checkout")
    args = parser.parse_args()

    catalog = load_catalog(args.catalog)
    report = build_report(catalog, implemented_controls())
    REPORT_PATH.write_text(report + "\n")
    print(report)
    print(f"\nReport written to {REPORT_PATH}")


if __name__ == "__main__":
    main()
