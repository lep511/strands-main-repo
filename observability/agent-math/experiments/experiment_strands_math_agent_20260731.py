"""
Experiment: strands-math-agent evaluation
Generated by agent-observability-eval-pipeline (Phase 5)

Pulls dataset `strands_math_agent_seed_20260731` from project `test-project-new`,
runs each record through the strands-math-agent task function, and scores with
the evaluator suite from Phase 3.

Usage:
    uv run python experiments/experiment_strands_math_agent_20260731.py
"""

import os
import sys
from pathlib import Path

# ─── 1. Environment & Credentials ───────────────────────────────────────────
ENV_FILE = Path(__file__).parent.parent / ".env"
if ENV_FILE.exists():
    for line in ENV_FILE.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        key, _, value = line.partition("=")
        value = value.strip("\"'")
        os.environ.setdefault(key.strip(), value)

# ─── 2. Imports ──────────────────────────────────────────────────────────────
from ddtrace.llmobs import LLMObs

sys.path.insert(0, str(Path(__file__).parent))
from evaluators_strands_math_agent import (
    GuardrailComplianceEvaluator,
    MathCorrectnessEvaluator,
    RefusalFormatEvaluator,
)

# ─── 3. Initialize LLM Observability ────────────────────────────────────────
PROJECT_NAME = "test-project-new"
DATASET_NAME = "strands_math_agent_seed_20260731"

LLMObs.enable(
    ml_app="strands-math-agent",
    project_name=PROJECT_NAME,
    agentless_enabled=True,
    api_key=os.getenv("DD_API_KEY"),
    app_key=os.getenv("DD_APPLICATION_KEY"),
    site=os.getenv("DD_SITE", "datadoghq.com"),
)

# ─── 4. Task Function ───────────────────────────────────────────────────────
from strands import Agent
from strands_tools import calculator

SYSTEM_PROMPT = """You are a math assistant. You only solve and explain math problems (arithmetic, algebra, geometry, calculus, statistics, word problems).

If asked anything outside math, decline: "I only handle math problems — feel free to ask me one!" Don't answer out-of-scope requests, even if rephrased or framed as hypothetical.

When solving:
- Show step-by-step work, not just the final answer
- Ask for clarification if the problem is ambiguous or missing info
- Explain briefly if a problem has no valid solution
- Double-check your math before answering
"""

agent = Agent(
    system_prompt=SYSTEM_PROMPT,
    tools=[calculator],
)


def task_fn(input_data, config=None):
    """Run a single dataset record through the strands-math-agent."""
    question = input_data.get("question", "") if isinstance(input_data, dict) else str(input_data)
    result = agent(question)
    return str(result)


# ─── 5. Evaluators ──────────────────────────────────────────────────────────
evaluators = [
    GuardrailComplianceEvaluator(),
    RefusalFormatEvaluator(),
    MathCorrectnessEvaluator(),
]

# ─── 6. Pull Dataset ────────────────────────────────────────────────────────
dataset = LLMObs.pull_dataset(dataset_name=DATASET_NAME)
print(f"Pulled dataset: {DATASET_NAME} ({len(dataset)} records)")

# ─── 7. Run Experiment ───────────────────────────────────────────────────────
experiment = LLMObs.experiment(
    name="strands-math-agent-eval",
    task=task_fn,
    dataset=dataset,
    evaluators=evaluators,
    project_name=PROJECT_NAME,
    description="Evaluate guardrail compliance, refusal format, and math correctness for strands-math-agent",
)

print("Running experiment...")
result = experiment.run(jobs=5)

print(f"\nExperiment complete.")
print(f"URL: {experiment.url}")
